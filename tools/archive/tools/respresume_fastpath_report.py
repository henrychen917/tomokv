#!/usr/bin/env python3
"""Render docs/respresume/fastpath.md from the PRE/POST objdump inventories.

Inputs (all produced by committed tools):
  <pre>/disassembly.tsv, <post>/disassembly.tsv   tools/respresume_artifacts.py
  <pre>/fast-path.json,  <post>/fast-path.json   tools/respresume_trace.py (GDB, copied ELF bytes)
  fastpath.json                                tools/respresume_fastpath.py (dispatcher windows)
"""
import argparse
import csv
import json
from pathlib import Path
import re


def rows(tsv):
    with tsv.open() as f:
        return list(csv.DictReader(f, delimiter='\t'))


def parser_key(name):
    ns = 'tomo_db0' if name.startswith('tomo_db0::') else 'tomo'
    limited = 'resp_parse_t<true' in name
    return ns, limited, '.cold' in name


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('pre', type=Path)
    ap.add_argument('post', type=Path)
    ap.add_argument('windows', type=Path)
    ap.add_argument('output', type=Path)
    args = ap.parse_args()
    pre_rows, post_rows = rows(args.pre / 'disassembly.tsv'), rows(args.post / 'disassembly.tsv')
    traces = {}
    for tag, d in (('pre', args.pre), ('post', args.post)):
        for r in json.loads((d / 'fast-path.json').read_text()):
            traces[(tag, r['address'], r['command'])] = r
    out = []
    w = out.append
    w('# respresume complete-frame fast path (objdump of build/tomokv)\n')
    w('Generated by `tools/respresume_fastpath_report.py`; every number below is reproducible from')
    w('the committed tools and binaries named in `pre/binary.sha256` and `post/binary.sha256`.\n')
    w('## resp_parse_t clones\n')
    w('Executed instructions: a complete `GET k` / `SET k v` frame traced by GDB through the')
    w("clone's own copied ELF bytes (`tools/respresume_trace.py`). Canary = `mov %fs:0x28`;")
    w('chk_fail = references to `__stack_chk_fail`.\n')
    w('| ns | instantiation | part | PRE addr | POST addr | bytes PRE->POST | static insns PRE->POST '
      '| canary PRE->POST | chk_fail PRE->POST | GET PRE->POST | SET PRE->POST |')
    w('|---|---|---|---|---|---|---|---|---|---|---|')
    groups = {}
    for tag, rs in (('pre', pre_rows), ('post', post_rows)):
        for r in rs:
            if 'resp_parse_t<' in r['symbol']:
                groups.setdefault(parser_key(r['symbol']) + (tag,), []).append(r)
    totals = dict(pre_bytes=0, post_bytes=0, pre_canary=0, post_canary=0, pre_chk=0, post_chk=0)
    for key in sorted({k[:3] for k in groups}):
        pre = sorted(groups.get(key + ('pre',), []), key=lambda r: int(r['address'], 16))
        post = sorted(groups.get(key + ('post',), []), key=lambda r: int(r['address'], 16))
        assert len(pre) == len(post), key
        for a, b in zip(pre, post):
            ns, limited, cold = key
            inst = ('<true>' if limited else '<false>') + ' -> ' + ('<true, true>' if limited else '<false, true>')
            get = set_ = '-'
            if not cold:
                get = f"{traces[('pre', a['address'], 'GET')]['instructions']} -> {traces[('post', b['address'], 'GET')]['instructions']}"
                set_ = f"{traces[('pre', a['address'], 'SET')]['instructions']} -> {traces[('post', b['address'], 'SET')]['instructions']}"
            w(f"| {ns} | {inst} | {'cold' if cold else 'body'} | {a['address']} | {b['address']} | "
              f"{a['bytes']} -> {b['bytes']} | {a['static_instructions']} -> {b['static_instructions']} | "
              f"{a['canary_loads']} -> {b['canary_loads']} | {a['canary_fail_calls']} -> {b['canary_fail_calls']} | "
              f"{get} | {set_} |")
            totals['pre_bytes'] += int(a['bytes']); totals['post_bytes'] += int(b['bytes'])
            totals['pre_canary'] += int(a['canary_loads']); totals['post_canary'] += int(b['canary_loads'])
            totals['pre_chk'] += int(a['canary_fail_calls']); totals['post_chk'] += int(b['canary_fail_calls'])
    w(f"\nTotals over 18 clone parts: bytes {totals['pre_bytes']} -> {totals['post_bytes']}, "
      f"canary loads {totals['pre_canary']} -> {totals['post_canary']}, __stack_chk_fail references "
      f"{totals['pre_chk']} -> {totals['post_chk']}.\n")
    windows = json.loads(args.windows.read_text())
    w('## parse_and_dispatch / r7_parse_and_dispatch clones\n')
    w('Window = call-free path from the `op->rbuf_off` store to the default-limit parser call,')
    w("through the `'*'` compare (`tools/respresume_fastpath.py`; each path is listed in")
    w('`fastpath.json`). Total = window + the traced body of the clone it calls. Stores in the')
    w('window are the `rbuf_off` store itself in every clone.\n')
    w('| clone | bytes PRE->POST | static insns PRE->POST | window PRE->POST | window stores PRE->POST '
      '| GET total PRE->POST | SET total PRE->POST |')
    w('|---|---|---|---|---|---|---|')
    worst = dict(GET=-10**9, SET=-10**9)
    for c in windows['clones']:
        m = re.search(r'((?:r7_)?parse_and_dispatch<[^()]*>)\((?:tomo|tomo_db0)::Client\*\)(.*)$', c['name'])
        name = m[1] + m[2]
        ns = 'tomo_db0::' if 'tomo_db0::' in c['name'] else 'tomo::'
        w(f"| `{ns}{name}` | {c['pre_bytes']} -> {c['post_bytes']} | {c['pre_static']} -> {c['post_static']} | "
          f"{c['pre_window']} -> {c['post_window']} | {c['pre_window_stores']} -> {c['post_window_stores']} | "
          f"{c['pre_GET_total']} -> {c['post_GET_total']} | {c['pre_SET_total']} -> {c['post_SET_total']} |")
        for cmd in ('GET', 'SET'):
            worst[cmd] = max(worst[cmd], c[f'post_{cmd}_total'] - c[f'pre_{cmd}_total'])
    cold = [r for r in post_rows if re.search(r'parse_and_dispatch<[^()]*>\((tomo|tomo_db0)::Client\*\).*\.cold', r['symbol'])]
    w(f"\nWorst per-clone change of the complete-frame parse (window + parser): GET {worst['GET']:+d}, "
      f"SET {worst['SET']:+d} instructions (negative = fewer). {len(windows['clones'])} dispatcher bodies; "
      f"their {len(cold)} `.cold` parts hold no complete-frame instruction.\n")
    args.output.write_text('\n'.join(out) + '\n')
    print(args.output, worst)


if __name__ == '__main__':
    main()
