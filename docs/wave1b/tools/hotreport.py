#!/usr/bin/env python3
"""wave1b: per-body attribution of every changed HOT body (final default build vs origin/cpp 1ba80bd4e),
from attribute.py's JSON. Adapted from cx-wave1 docs/wave1/tools/hotreport.py: no perfex; the
cherry-picked climon fix (ec0317384) is its own class. usage: hotreport.py attr.json out.json out.tsv"""
import json, re, sys
from collections import Counter
r = json.load(open(sys.argv[1]))
REASONS = [
 (r'serve_suppressing|prepare_suppressing|climon_serve_suppressed|climon_prepare_suppressed|tracking_retire_plain', {
   'climonfix': 'climon fix ec0317384: the cold suppressing drain takes retire_plain (decided per connection); '
                'renamed instantiations (extra bool) replace the clientfix signatures'}),
 (r'r7_parse_and_dispatch|parse_and_dispatch', {
   'clientfix': 'clientfix: armed climon gate + ACL entry moved after the FLIP hold (tracking/SKIP receipt keyed by ROB number)',
   'racefix': 'racefix: ThreadCtx::note_command relaxed-atomic load/store counters (inlined)',
   'flipfix': 'flipfix: sampled-pass fingerprint publish moved out of line (FlipFingerprintWriter::publish_sampled_pass)',
   'savefix': 'savefix: lane-branch inlining drift only (no source change in parse_and_dispatch)'}),
 (r'flush_ready', {'clientfix': 'clientfix: writeback per-connection predicted-false mask gains the tracking bit (cold retirement drain)'}),
 (r'IoLoop::init', {'clientfix': 'clientfix: retire callback calls tracking_retire_read behind a predicted-false local-tracker test'}),
 (r'::execute<', {'racefix': 'racefix: note_command relaxed-atomic counters inlined into execute',
                  'savefix': 'savefix: owner admission/stale-forward hold (shutdown_snapshot_blocks_tasks)'}),
 (r'on_cqe', {'racefix': 'racefix: net_input_bytes relaxed load/store in the inlined recv completion paths'}),
 (r'fused_pass_impl|::sweep<|r7_sweep', {'savefix': 'savefix: owner-loop admission (blocking beat skipped while shutdown_snapshot_blocks_tasks)'}),
 (r'ExLoopT<.*>::run\(', {'savefix': 'savefix: blocking beat admission behind shutdown_snapshot_blocks_tasks'}),
 (r'drain_tasks', {}),
]
rows = []
for o in r:
    for x in o['rows']:
        if not x['hot']:
            continue
        lc, eq = x['lanes_changed'], x['merged_equals_lane']
        if x.get('climonfix'): k = 'climon-fix'
        elif x.get('r7_mirror_of'): k = 'R7-mirror'
        elif eq and set(eq) & set(lc): k = 'lane-identical'
        elif len(lc) > 1: k = 'composite'
        elif lc: k = 'lane-change-differs'
        else: k = 'UNATTRIBUTED'
        lanes = sorted(set(lc) | set(x.get('r7_mirror_of') or []) | ({'climonfix'} if x.get('climonfix') else set()))
        reason = []
        for pat, table in REASONS:
            if re.search(pat, x['name']):
                reason = [table[l] for l in lanes if l in table]
                if x.get('r7_mirror_of'):
                    reason.append('R7 envelope regenerated by tests/r7shadow_sync.py --write (d32c20a20) mirrors '
                                  + '+'.join(x['r7_mirror_of']) + "'s source edit")
                break
        struct = 'PRE' if x['targets_equal_pre'] else (','.join(x['targets_equal_lane']) or 'new')
        rows.append(dict(object=o['object'], name=x['name'], kind=x['kind'], pre_size=x['pre_size'],
                         post_size=x['post_size'], attribution=k, lanes=lanes,
                         equals_lane_body=sorted(set(eq) & set(lc)), equals_b4=x['merged_equals_b4'],
                         call_targets_as=struct, reason='; '.join(reason) or 'UNEXPLAINED'))
json.dump(rows, open(sys.argv[2], 'w'), indent=1)
with open(sys.argv[3], 'w') as f:
    f.write('object\tattribution\tlanes\tequals_lane_body\tequals_b4\tcall_targets_as\tkind\tpre_size\tpost_size\tbody\treason\n')
    for x in rows:
        f.write('\t'.join([x['object'], x['attribution'], '+'.join(x['lanes']), '+'.join(x['equals_lane_body']) or '-',
                           str(x['equals_b4']), x['call_targets_as'], x['kind'], str(x['pre_size']), str(x['post_size']),
                           x['name'], x['reason']]) + '\n')
print(Counter(x['attribution'] for x in rows), len(rows), 'unexplained:', sum(x['reason'] == 'UNEXPLAINED' for x in rows))
