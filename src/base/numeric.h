// A "diy fp": the value f * 2^e, with f carried at full 64-bit width so the multiply below keeps
// the extra guard bits Grisu2 needs.
struct Fp {
    uint64_t f;
    int e;
};

struct CachedPow {
    uint64_t f;
    int16_t e;
    int16_t k;   // decimal exponent: this row is 10^k, rounded to 64 significant bits
};

