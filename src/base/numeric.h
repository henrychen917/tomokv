// Decimal digits, then redis's own fixed/scientific rule. u64_to_dec lives in the RESP header, so
// the plain-integer paths are spelled out here to keep this unit free of protocol includes.
inline uint32_t u64_digits(char* out, uint64_t value) {
    char scratch[20];
    int n = 0;
    do { scratch[n++] = static_cast<char>('0' + value % 10); value /= 10; } while (value);
    for (int i = 0; i < n; i++) out[i] = scratch[n - 1 - i];
    return static_cast<uint32_t>(n);
}

// THE canonical double text, for RESP2 bulk scores and the RESP3 "," form alike (redis renders
// both from one d2string). Derived from the 7.4 binary's OBSERVED output, not from its source:
//
//   * nan / inf / -inf and a signed zero are spelled out;
//   * an INTEGRAL value with |v| <= 4611686018427387904 (redis's (double)(LLONG_MAX/2) bound,
//     probed inclusive at both ends) prints as a plain integer -- so 1e18 is "1000000000000000000",
//     not "1e+18", and 2^62 prints its exact 19 digits while 2^63 does not;
//   * everything else is the Grisu2 digit string D with v = D x 10^K, rendered fixed when K is
//     small and scientific otherwise, with an unpadded signed exponent.
//
// Callers must give at least kDoubleTextMax bytes; the `cap` argument is kept so a call site
// reads as a bounded write, and the sizes are static_asserted where reply buffers are declared.
inline constexpr size_t kDoubleTextMax = 40;

inline uint32_t redis_double_text(char* out, size_t cap, double value) {
    if (std::isnan(value)) { std::memcpy(out, "nan", 3); return 3; }
    if (std::isinf(value)) {
        if (value < 0) { std::memcpy(out, "-inf", 4); return 4; }
        std::memcpy(out, "inf", 3); return 3;
    }
    if (value == 0) {
        if (std::signbit(value)) { std::memcpy(out, "-0", 2); return 2; }
        out[0] = '0';
        return 1;
    }
    // The integral fast path. The bound is redis's (double)(LLONG_MAX/2), which rounds to 2^62.
    constexpr double kIntegralBound = 4611686018427387904.0;
    if (value >= -kIntegralBound && value <= kIntegralBound) {
        const long long integral = static_cast<long long>(value);
        if (static_cast<double>(integral) == value) {
            char* q = out;
            unsigned long long magnitude;
            if (integral < 0) {
                *q++ = '-';
                magnitude = 0ULL - static_cast<unsigned long long>(integral);
            } else {
                magnitude = static_cast<unsigned long long>(integral);
            }
            q += u64_digits(q, magnitude);
            return static_cast<uint32_t>(q - out);
        }
    }

    const bool negative = value < 0;
    char digits[24];
    int k = 0;
    const int ndigits = dtoa::grisu2_digits(negative ? -value : value, digits, k);

    const int decimal_exponent = k + ndigits - 1;   // value == 0.d... x 10^(decimal_exponent+1)
    const int magnitude = decimal_exponent < 0 ? -decimal_exponent : decimal_exponent;
    // Neither branch below can be long. The plain-integer arm pads at most 7 zeroes (that is its
    // own entry condition), the fixed arm at most 3 leading zeroes (a magnitude under 4 is what
    // lets it run at all), and the scientific arm writes a 3-digit exponent. Worst case is
    // sign + 18 digits + 7 padding zeroes = 26 bytes, so kDoubleTextMax covers every value and no
    // length check is needed on the hot path.
    (void)cap;
    char* q = out;
    if (negative) *q++ = '-';
    if (k >= 0 && magnitude < ndigits + 7) {          // plain integer, zero padded
        std::memcpy(q, digits, static_cast<size_t>(ndigits));
        q += ndigits;
        std::memset(q, '0', static_cast<size_t>(k));
        q += k;
    } else if (k < 0 && (k > -7 || magnitude < 4)) {  // fixed point
        const int offset = ndigits + k;
        if (offset <= 0) {
            *q++ = '0';
            *q++ = '.';
            std::memset(q, '0', static_cast<size_t>(-offset));
            q += -offset;
            std::memcpy(q, digits, static_cast<size_t>(ndigits));
            q += ndigits;
        } else {
            std::memcpy(q, digits, static_cast<size_t>(offset));
            q += offset;
            *q++ = '.';
            std::memcpy(q, digits + offset, static_cast<size_t>(ndigits - offset));
            q += ndigits - offset;
        }
    } else {                                          // scientific, exponent not zero padded
        *q++ = digits[0];
        if (ndigits > 1) {
            *q++ = '.';
            std::memcpy(q, digits + 1, static_cast<size_t>(ndigits - 1));
            q += ndigits - 1;
        }
        *q++ = 'e';
        *q++ = decimal_exponent < 0 ? '-' : '+';
        q += u64_digits(q, static_cast<uint64_t>(magnitude));
    }
    return static_cast<uint32_t>(q - out);
}

// ------------------------------------------------------------------ parsing

// The redis getDoubleFromObject grammar, used wherever a double is a VALUE: ZADD/ZINCRBY scores,
// ZUNIONSTORE weights, GEO coordinates and distances. Redis calls strtod and then refuses the
// empty string, a leading space, trailing text, a magnitude strtod flagged as out of range, and
// NaN. It does NOT refuse what strtod itself accepts, so "0x10" is 16 and "+5" is 5.
//
// The slice is copied because strtod needs a terminator; an embedded NUL therefore leaves trailing
// text behind and is refused, which is the same answer redis gives (it compares the consumed
// length against the whole argument length).
inline bool parse_double_strict(Slice s, double& out) {
    char text[512];
    if (s.n == 0 || s.n >= sizeof(text)) return false;
    std::memcpy(text, s.p, s.n);
    text[s.n] = '\0';
    if (std::isspace(static_cast<unsigned char>(text[0]))) return false;

    errno = 0;
    char* end = nullptr;
    const double value = std::strtod(text, &end);
    if (end != text + s.n) return false;
    if (errno == ERANGE && (std::isinf(value) || std::fpclassify(value) == FP_ZERO)) return false;
    if (std::isnan(value)) return false;
    out = value;
    return true;
}

// The bare strtod redis uses for score RANGES (zslParseRange) and for numeric SORT. Everything the
// strict grammar refuses is accepted here except NaN and trailing text:
//
//   ""       -> 0      (strtod consumed nothing, and the terminator is where it stopped)
//   " 5"     -> 5      (strtod skips leading whitespace)
//   "0x10"   -> 16
//   "1e309"  -> +inf   (ERANGE is not consulted)
//   "5\0 5"  -> 5      (the C string ends at the NUL, so nothing trails it)
//
// The NUL case is not an oversight to be corrected: redis stops at the same byte and answers 5,
// and a range that answered an error where the reference answers a result would silently change
// which members a client sees.
inline bool parse_double_lenient(Slice s, double& out) {
    char text[512];
    if (s.n >= sizeof(text)) return false;
    std::memcpy(text, s.p, s.n);
    text[s.n] = '\0';

    char* end = nullptr;
    const double value = std::strtod(text, &end);
    if (*end != '\0' || std::isnan(value)) return false;
    out = value;
    return true;
}

