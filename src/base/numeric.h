inline constexpr uint64_t kTens[20] = {
    10000000000000000000ULL, 1000000000000000000ULL, 100000000000000000ULL,
    10000000000000000ULL,    1000000000000000ULL,    100000000000000ULL,
    10000000000000ULL,       1000000000000ULL,       100000000000ULL,
    10000000000ULL,          1000000000ULL,          100000000ULL,
    10000000ULL,             1000000ULL,             100000ULL,
    10000ULL,                1000ULL,                100ULL,
    10ULL,                   1ULL,
};

// The top 64 bits of a*b, with the discarded half rounded in. Grisu2 depends on this exact
// rounding: it is what makes the boundary arithmetic below conservative rather than merely close.
inline Fp fp_multiply(Fp a, Fp b) {
    const unsigned __int128 product = static_cast<unsigned __int128>(a.f) * b.f;
    const uint64_t high = static_cast<uint64_t>(product >> 64);
    const uint64_t low = static_cast<uint64_t>(product);
    return Fp{high + (low >> 63), a.e + b.e + 64};
}

// The cached power whose product with a value of this binary exponent lands the result in
// [2^-60, 2^-32) of the "one" unit -- the window Grisu2's two digit loops are written for.
inline int cached_pow_index(int exponent) {
    // 1/log2(10): converts a binary exponent into the decimal exponent that lands nearby, so the
    // scan below starts on or next to the answer instead of walking 87 rows.
    // The truncation happens BEFORE the offset is added, and the scan below is not free to land
    // wherever it likes: the 8-decimal row spacing is ~26.6 binary and the window is 29 wide, so
    // for some exponents two adjacent rows both qualify and the starting point decides which one
    // is used -- and which one is used decides the last digit.
    constexpr double kInvLog2Of10 = 0.30102999566398114;
    int index = (static_cast<int>(-(exponent + 87) * kInvLog2Of10) + 348) / 8;
    if (index < 0) index = 0;
    if (index > 86) index = 86;
    for (;;) {
        const int scaled = exponent + kPow10[index].e + 64;
        if (scaled < -60) { index++; continue; }
        if (scaled > -32) { index--; continue; }
        return index;
    }
}

// Trim the last digit down while every candidate still round-trips and the shorter one is closer
// to w. This is Grisu2's "weeding" step; without it the last digit is merely inside the boundary
// interval rather than the one redis prints.
inline void weed_last_digit(char* digits, int count, uint64_t delta, uint64_t remainder,
                            uint64_t unit, uint64_t distance) {
    while (remainder < distance && delta - remainder >= unit &&
           (remainder + unit < distance || distance - remainder > remainder + unit - distance)) {
        digits[count - 1]--;
        remainder += unit;
    }
}

// Writes the decimal digits of `value` (finite, non-zero) into `digits` and sets `k` so that
// value == digits * 10^k. Returns the digit count (at most 18). Sign is the caller's business.
inline int grisu2_digits(double value, char* digits, int& k) {
    uint64_t bits;
    std::memcpy(&bits, &value, sizeof(bits));
    const int biased = static_cast<int>((bits >> 52) & 0x7FF);
    const uint64_t mantissa = bits & ((uint64_t{1} << 52) - 1);

    Fp w = biased ? Fp{mantissa + (uint64_t{1} << 52), biased - 1075} : Fp{mantissa, -1074};

    // The normalized boundaries: the halfway points to the neighbouring doubles, both carried at
    // the same exponent so their difference is the interval any correct digit string may land in.
    Fp upper{(w.f << 1) + 1, w.e - 1};
    while ((upper.f & (uint64_t{1} << 53)) == 0) { upper.f <<= 1; upper.e--; }
    upper.f <<= 10;
    upper.e -= 10;

    const int lower_shift = (w.f == (uint64_t{1} << 52)) ? 2 : 1;
    Fp lower{(w.f << lower_shift) - 1, w.e - lower_shift};
    lower.f <<= lower.e - upper.e;
    lower.e = upper.e;

    while ((w.f & (uint64_t{1} << 63)) == 0) { w.f <<= 1; w.e--; }

    const CachedPow& power = kPow10[cached_pow_index(upper.e)];
    const Fp scale{power.f, power.e};
    w = fp_multiply(w, scale);
    upper = fp_multiply(upper, scale);
    lower = fp_multiply(lower, scale);
    // One unit in from each side: the multiply rounded, so the interval is only trustworthy when
    // it is narrowed by the rounding error it may have gained.
    lower.f++;
    upper.f--;
    k = -power.k;

    const uint64_t distance = upper.f - w.f;
    uint64_t delta = upper.f - lower.f;
    const int shift = -upper.e;
    const uint64_t one = uint64_t{1} << shift;

    uint64_t integral = upper.f >> shift;
    uint64_t fractional = upper.f & (one - 1);
    int count = 0;

    // Digits above the decimal point of the scaled value: kappa counts down from 10 because the
    // window above guarantees the integral part is under 10^10.
    int kappa = 10;
    for (const uint64_t* divisor = kTens + 10; kappa > 0; divisor++) {
        const uint64_t div = *divisor;
        const unsigned digit = static_cast<unsigned>(integral / div);
        if (digit || count) digits[count++] = static_cast<char>('0' + digit);
        integral -= digit * div;
        kappa--;
        const uint64_t remainder = (integral << shift) + fractional;
        if (remainder <= delta) {
            k += kappa;
            weed_last_digit(digits, count, delta, remainder, div << shift, distance);
            return count;
        }
    }

    // Digits below it.
    const uint64_t* unit = kTens + 18;
    for (;;) {
        fractional *= 10;
        delta *= 10;
        kappa--;
        const unsigned digit = static_cast<unsigned>(fractional >> shift);
        if (digit || count) digits[count++] = static_cast<char>('0' + digit);
        fractional &= one - 1;
        if (fractional < delta) {
            k += kappa;
            weed_last_digit(digits, count, delta, fractional, one, distance * *unit);
            return count;
        }
        unit--;
    }
}

